export default function PrivacyModal() {
    const [isOpen, setIsOpen] = useState(false);

    useEffect(() => {
        const open = () => setIsOpen(true);
        window.addEventListener('openPrivacyModal', open);
        return () => window.removeEventListener('openPrivacyModal', open);
    }, []);

    if (!isOpen) return null;

    return (
        <div className="privacy-modal-overlay" onClick={() => setIsOpen(false)}>
            <div className="privacy-modal" onClick={(e) => e.stopPropagation()}>
                <div className="modal-header">
                    <strong className="modal-title">개인정보처리방침</strong>
                    <button className="modal-close" onClick={() => setIsOpen(false)}>
                        ✕
                    </button>
                </div>
                <div className="modal-body">
                    {PRIVACY_CONTENT.map((section, i) => (
                        <div key={i} className="privacy-section">
                            {section.title && <strong className="section-title">{section.title}</strong>}
                            <p className="section-body">{section.body}</p>
                        </div>
                    ))}
                </div>
            </div>
        </div>
    );
}
